  /* -------------------------------------------------------------------
     5-1. 이번 면접에 쓸 활동 뽑기
     카드가 쌓이면 모델에게 전부 넘기지 않습니다.
     프로그램이 먼저 균형을 맞춰 무작위로 뽑아 그것만 넘깁니다.
     이러면 연습할 때마다 다른 질문이 나오고, 매 차례 보내는 양도 줄어듭니다.
     ------------------------------------------------------------------- */
  function 섞기(arr) {
    var a = arr.slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }

  /* 구분(창체·세특·행특)이 한쪽에 몰리지 않게 집되, 가진 수에 비례해서 집는다.
     돌아가며 하나씩 집으면 항목이 적은 통의 활동이 과하게 자주 뽑힌다.
     예를 들어 창체에 하나, 세특에 셋이 있는데 번갈아 집으면
     창체의 그 하나가 세 배 자주 나온다. */
  function 구분별로집기(목록, 개수) {
    if (개수 <= 0) return [];
    var 전체 = 섞기(목록);
    if (전체.length <= 개수) return 전체;

    var 통 = {};
    전체.forEach(function (a) {
      var k = a.구분 || a.출처 || "기타";
      (통[k] = 통[k] || []).push(a);
    });
    var 키들 = Object.keys(통);

    // 가진 수에 비례해 먼저 배분
    var 뽑힘 = [];
    키들.forEach(function (k) {
      var 몫 = Math.floor(개수 * 통[k].length / 전체.length);
      뽑힘 = 뽑힘.concat(통[k].splice(0, 몫));
    });

    // 남은 자리는 남은 것들 중에서 고르게
    var 남은 = [];
    키들.forEach(function (k) { 남은 = 남은.concat(통[k]); });
    남은 = 섞기(남은);
    return 뽑힘.concat(남은.slice(0, 개수 - 뽑힘.length));
  }

  /* 지원 학과와 가까운 활동을 우선 뽑습니다.
     학과와 먼 활동도 한두 개는 넣습니다. 학업 역량은 그런 데서도 드러나니까요.
     다만 그것이 면접의 절반을 차지하면 엉뚱한 면접이 됩니다. */
  function 면접용뽑기(활동들, 뽑을개수) {
    var N = 뽑을개수 || 10;
    var 전체 = (활동들 || []).slice();
    if (전체.length <= N) return 섞기(전체);

    var 높음 = [], 보통 = [], 낮음 = [];
    전체.forEach(function (a) {
      var r = a.학과관련;
      if (r === "낮음") 낮음.push(a);
      else if (r === "보통") 보통.push(a);
      else 높음.push(a);   // 등급이 없는 옛 카드는 높음으로 본다
    });

    // 학과와 먼 활동은 많아야 하나. 절반쯤은 아예 넣지 않는다.
    var 낮음몫 = Math.min(낮음.length, (N >= 10 && Math.random() < 0.5) ? 1 : 0);
    var 보통몫 = Math.min(보통.length, Math.round(N * 0.3));  // 세 개 중 하나쯤
    var 높음몫 = N - 낮음몫 - 보통몫;

    // 높음이 모자라면 보통에서 메운다
    if (높음몫 > 높음.length) {
      보통몫 = Math.min(보통.length, 보통몫 + (높음몫 - 높음.length));
      높음몫 = 높음.length;
    }
    var 뽑힘 = []
      .concat(구분별로집기(높음, 높음몫))
      .concat(구분별로집기(보통, 보통몫))
      .concat(구분별로집기(낮음, 낮음몫));

    // 그래도 모자라면 남은 데서 아무거나 채운다
    if (뽑힘.length < N) {
      var 이미 = {};
      뽑힘.forEach(function (a) { 이미[a.id] = true; });
      var 나머지 = 섞기(전체.filter(function (a) { return !이미[a.id]; }));
      뽑힘 = 뽑힘.concat(나머지.slice(0, N - 뽑힘.length));
    }
    return 섞기(뽑힘);
  }

